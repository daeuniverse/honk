/// Ingress ifindex for locally-generated packets (not from any interface).
const NOWHERE_IFINDEX: u32 = 0;
use crate::auxiliary::{
    AuxPrep, IDENTITY_MISMATCH as TOKEN_IDENTITY_MISMATCH, prep_redirect_to_control_plane,
};

#[inline(always)]
fn skb_ingress_ifindex(ctx: &TcContext) -> u32 {
    unsafe { (*ctx.skb.skb).ingress_ifindex }
}

#[inline(always)]
fn skb_mark(ctx: &TcContext) -> u32 {
    unsafe { (*ctx.skb.skb).mark }
}

/// A Redirect generated by the local stack must not leave an egress honk
/// owns: it teaches peers to bypass the gateway. Forwarded Redirects keep
/// their pass-through verdict. A single-homed shared interface carries only
/// `wan_egress`, so both egress hooks need this suppression.
#[inline(always)]
fn local_ndp_redirect(ctx: &TcContext, ret: c_long) -> bool {
    ret == PASS_NDP_REDIRECT && skb_ingress_ifindex(ctx) == NOWHERE_IFINDEX
}

const DOMAIN_UDP_OTHER: u32 = 2;
const DOMAIN_DEFAULT: u32 = 0;

/// Check whether the selected outbound is currently alive.
///
/// DNS uses userspace fallback/rejection regardless of transport, so destination
/// port 53 is exempt. Other traffic consults `OUTBOUND_CONNECTIVITY_MAP`.
///
/// Map key layout (mirrors C):
///   key = outbound * 6 + domain_idx * 2 + ip_idx
///   - domain_idx: 0 = TCP, 1 = DNS UDP, 2 = data UDP
///   - ip_idx: 0 = IPv4, 1 = IPv6
#[inline(always)]
pub fn wan_outbound_is_alive(ctx: &TcContext, outbound: u8, l4proto: u8, dport: u16) -> bool {
    if dport == 53 {
        return true;
    }

    let domain_idx: u32 = match l4proto {
        IPPROTO_UDP => DOMAIN_UDP_OTHER,
        _ => DOMAIN_DEFAULT,
    };

    let proto = ctx.skb.protocol() as u16;
    let ip_idx: u32 = if proto == ETH_P_IP.to_be() { 0 } else { 1 };

    let key: u32 = (outbound as u32)
        .wrapping_mul(6)
        .wrapping_add(domain_idx.wrapping_mul(2))
        .wrapping_add(ip_idx);

    // OUTBOUND_CONNECTIVITY_MAP is `Array<u64, 1536>` — key is u32 index.
    match OUTBOUND_CONNECTIVITY_MAP.get(key) {
        Some(val) => *val != 0,
        None => true, // absent entry → assume alive
    }
}

/// Convenience: true when the packet is from the control plane (any detection
/// method).
#[inline(always)]
pub fn is_control_plane(ctx: &TcContext) -> bool {
    if let Some(pid_pname) = socket_identity::lookup(ctx) {
        let param = PARAM.load();
        if param.control_plane_pid != 0 && pid_pname.pid == param.control_plane_pid {
            return true;
        }
    }

    let param = PARAM.load();
    let mark = skb_mark(ctx);

    if param.dae_socket_mark != 0 && mark == param.dae_socket_mark {
        return true;
    }

    false
}

/// Egress redirect to the control plane (dae0 interface).
///
/// bpf_redirect_peer is NOT supported in the egress direction.
#[inline(always)]
pub fn redirect_to_control_plane_egress() -> Verdict {
    let param = PARAM.load();
    Ok(unsafe { bpf_redirect(param.dae0_ifindex, 0) } as c_long)
}

/// LAN egress: server/local FIN/RST must keep the existing client-side TCP
/// lifecycle in sync; unsolicited reverse SYNs have no publication authority.
///
/// Also drops NDP REDIRECT packets originated from localhost to prevent
/// kernel ND proxy from interfering with dae's routing.
///
/// #[inline(never)]: shared by lan_egress_l2/l3. Shallow call chain.
#[inline(never)]
pub fn do_tproxy_lan_egress(ctx: &TcContext, link_h_len: u32) -> Verdict {
    let scratch_key: u32 = 0;
    let pkt = match unsafe { PKT_SCRATCH_KEY.get_ptr_mut(scratch_key) } {
        Some(ptr) => unsafe { &mut *ptr },
        None => return Err(TC_ACT_SHOT),
    };

    let ret = parse_packet(ctx, link_h_len, pkt);
    if ret != 0 {
        if ret < 0 || local_ndp_redirect(ctx, ret) {
            return Err(TC_ACT_SHOT);
        }
        return Err(TC_ACT_UNSPEC);
    }

    // Broadcast/multicast (DHCPOFFER, mDNS, NetBIOS) is never conn-tracked.
    if crate::transport::dst_is_special(pkt, link_h_len) {
        return Err(TC_ACT_UNSPEC);
    }

    match pkt.l4proto {
        IPPROTO_TCP => {
            let mut reversed_key: TuplesKey = unsafe { mem::zeroed() };
            copy_reversed_tuples(&pkt.tuples.five, &mut reversed_key);
            let tcp_publisher = crate::contrack::tcp::TcpPublisher::new(&reversed_key);
            let seen = mark_tcp_seen(
                &reversed_key,
                &pkt.tcph,
                None, // outbound
                None, // mark
                None, // must
                None, // mac
                0,    // dscp
                None, // pname
                0,    // pid
                0,
                &tcp_publisher,
            );
            if seen.is_none() && crate::contrack::tuple_unavailable(&reversed_key) {
                return Err(TC_ACT_SHOT);
            }
        }
        IPPROTO_UDP => {
            // Pure L2 bridging can skip inet prerouting: queued DNS must never escape natively.
            if pkt.tuples.five.dst_port == 53
                && UdpDnsRoute::from_nfqueue_mark(unsafe { (*ctx.skb.skb).mark }).is_some()
            {
                return Err(TC_ACT_SHOT);
            }
            // Skip DNS traffic to reduce state churn.
            if u16::from_be_bytes(pkt.udph.src) == 53 || u16::from_be_bytes(pkt.udph.dst) == 53 {
                return Err(TC_ACT_UNSPEC);
            }
            let mut reversed_key: TuplesKey = unsafe { mem::zeroed() };
            copy_reversed_tuples(&pkt.tuples.five, &mut reversed_key);
            // A reply leaving dae0 answers a flow honk already owns. Creating a
            // WAN-direction entry for a peer the client never contacted would
            // make the client's first packet to that peer bypass the proxy.
            let dae0_ifindex = PARAM.load().dae0_ifindex;
            let learn = dae0_ifindex == 0 || skb_ingress_ifindex(ctx) != dae0_ifindex;
            if !crate::contrack::udp::reverse_udp_available(&reversed_key, learn) {
                return Err(TC_ACT_SHOT);
            }
        }
        _ => {}
    }

    Ok(TC_ACT_UNSPEC)
}

/// WAN egress TCP handler: route new connections and cache the decision;
/// for established flows, reuse the cached routing.
#[inline(always)]
fn do_tproxy_wan_egress_tcp(
    ctx: &TcContext,
    link_h_len: u32,
    pkt: &mut crate::transport::ParsedPacket,
    syn: &crate::contrack::tcp::TcpPublisher,
) -> Verdict {
    let tuples = &pkt.tuples;
    let ethh = &pkt.ethh;
    let tcph = &pkt.tcph;
    let dns = tuples.five.dst_port == 53;
    let wire_pure_syn = is_new_tcp_connection(tcph);
    let fresh_publication = syn.is_fresh();
    let outbound: u8;
    let must: bool;
    let mark: u32;
    let routing_generation: u64;
    let trace_id: u32;

    let mut handoff_pname: Option<&[u8; TASK_COMM_LEN]> = None;
    let mut handoff_pid: u32 = 0;

    let mut mac = [0u8; 6];

    if fresh_publication {
        let proto = ctx.skb.protocol() as u16;
        let ip_version = if proto == ETH_P_IP.to_be() {
            IpVersionType::V4 as u8
        } else {
            IpVersionType::V6 as u8
        };

        let pid_pname_opt = socket_identity::lookup(ctx);
        if let Some(pid_pname) = pid_pname_opt {
            let param = PARAM.load();
            if pid_pname.pid == param.control_plane_pid {
                return Err(TC_ACT_UNSPEC);
            }

            handoff_pname = Some(&pid_pname.pname);
            handoff_pid = pid_pname.pid;
        }

        let route_mac = if link_h_len == ETH_HLEN {
            mac.copy_from_slice(&ethh.src_addr);
            Some(&mac)
        } else {
            None
        };

        let pname = pid_pname_opt.map(|pid_pname| &pid_pname.pname);
        crate::route::build_input(
            &mut pkt.routing_input,
            tuples,
            route_mac,
            L4ProtoType::Tcp as u8,
            ip_version,
            true,
        );
        let flags = crate::maps::datapath_flags();
        let (mut decision, generation) = match crate::route::route(
            &mut pkt.routing_input,
            pname,
            flags,
            &mut pkt.route_witness.output,
        ) {
            Ok(result) => result,
            Err(_) => return Err(TC_ACT_SHOT),
        };
        routing_generation = generation;

        decision.apply_mode_flags(flags, tuples.five.dst_port);
        outbound = decision.handoff_outbound();
        mark = decision.mark;
        must = decision.must != 0;
        let must_val = must as u8;

        let dscp = tuples.dscp;
        let (outbound_ptr, mark_ptr, must_ptr): (Option<&u8>, Option<&u32>, Option<&u8>) =
            if outbound == OUTBOUND_DIRECT && mark == 0 && !must && !dns {
                (None, None, None)
            } else {
                (Some(&outbound), Some(&mark), Some(&must_val))
            };

        let pname_bytes: Option<&[u8; TASK_COMM_LEN]> = handoff_pname;
        let ambiguous = pkt.route_witness.output.flags & honk_ebpf_common::ROUTE_TRACE_ENABLED != 0
            && (crate::maps::CONN_STATE_MAP.get_ptr(&tuples.five).is_some()
                || ROUTING_HANDOFF_MAP.get_ptr(&tuples.five).is_some());
        trace_id = if outbound == OUTBOUND_BLOCK
            || (outbound == OUTBOUND_DIRECT && mark == 0 && (!dns || must))
        {
            0
        } else {
            crate::route::capture(&mut pkt.route_witness, &tuples.five, 0, ambiguous)
        };

        let tcp_conn = mark_tcp_seen(
            &tuples.five,
            tcph,
            outbound_ptr,
            mark_ptr,
            must_ptr,
            Some(&mac),
            dscp,
            pname_bytes,
            handoff_pid,
            trace_id,
            syn,
        );

        if tcp_conn.is_none() {
            if crate::maps::tuple_retiring(&tuples.five) {
                return Err(TC_ACT_SHOT);
            }
            if outbound == OUTBOUND_DIRECT && mark == 0 {
                return Err(TC_ACT_UNSPEC);
            }
            return Err(TC_ACT_SHOT);
        }
    } else {
        routing_generation = 0;
        trace_id = 0;
        let tcp_conn = mark_tcp_seen(
            &tuples.five,
            tcph,
            None, // outbound
            None, // mark
            None, // must
            None, // mac
            0,    // dscp
            None, // pname
            0,    // pid
            0,
            syn,
        );

        if let Some(conn) = tcp_conn {
            // Check has_routing from raw u64: bit 56.
            let meta_raw = unsafe { conn.meta.raw };
            if ((meta_raw >> 56) & 1) != 0 {
                outbound = (meta_raw & 0xFF) as u8;
                mark = ((meta_raw >> 8) & 0xFFFFFFFF) as u32;
                must = ((meta_raw >> 40) & 1) != 0;
                handoff_pname = Some(&conn.pname);
                handoff_pid = conn.pid;
                mac.copy_from_slice(&conn.mac);
                pkt.incarnation = conn.incarnation;
            } else {
                // No cached routing — direct connection, pass through.
                return Err(TC_ACT_UNSPEC);
            }
        } else {
            if wire_pure_syn || crate::contrack::tuple_unavailable(&tuples.five) {
                return Err(TC_ACT_SHOT);
            }
            // No state at all — pass through.
            return Err(TC_ACT_UNSPEC);
        }
    }

    // Egress runs after route lookup: a nonzero direct mark needs a fresh
    // userspace dial, including terminal DNS rules.
    if outbound == OUTBOUND_DIRECT && mark == 0 && (!dns || must) {
        ctx.set_mark(mark);
        return Err(TC_ACT_OK);
    } else if outbound == OUTBOUND_BLOCK {
        return Err(TC_ACT_SHOT);
    }

    if fresh_publication && !wan_outbound_is_alive(ctx, outbound, IPPROTO_TCP, tuples.five.dst_port)
    {
        return Err(TC_ACT_SHOT);
    }

    let aux = if fresh_publication {
        AuxPrep::Publish
    } else if wire_pure_syn {
        AuxPrep::Existing
    } else {
        AuxPrep::Refresh
    };
    let prepare_result = prep_redirect_to_control_plane(
        ctx,
        link_h_len,
        tuples,
        ethh,
        1,
        aux,
        outbound,
        0,
        pkt.incarnation,
    );
    if prepare_result != 0 {
        return Err(TC_ACT_SHOT);
    }

    // Set cb marks for dae0peer_ingress.
    unsafe {
        (*ctx.skb.skb).cb[0] = TPROXY_MARK;
        (*ctx.skb.skb).cb[1] = 0;
        (*ctx.skb.skb).cb[2] = 0;
        (*ctx.skb.skb).cb[3] = if wire_pure_syn {
            pkt.incarnation as u32
        } else {
            0
        };
        (*ctx.skb.skb).cb[4] = if wire_pure_syn {
            (pkt.incarnation >> 32) as u32
        } else {
            0
        };
    }

    // Only fresh publication captures the immutable handoff snapshot.
    if fresh_publication {
        let Some(scratch) = UDP_DECISION_SCRATCH_MAP.get_ptr_mut(0) else {
            increment_bpf_stat(BpfStatsKey::RoutingHandoffInsertFailure);
            return Err(TC_ACT_SHOT);
        };
        // WAN inlining shares its bounded stack with the conntrack subprograms.
        let handoff: &mut RoutingHandoffEntry = unsafe { &mut (*scratch).handoff };
        unsafe { core::ptr::write_bytes(handoff, 0, 1) };
        handoff.last_seen_ns = unsafe { bpf_ktime_get_ns() };
        handoff.routing_generation = routing_generation;
        handoff.trace_id = trace_id;
        handoff.incarnation = pkt.incarnation;
        handoff.result.mark = mark;
        handoff.result.must = must as u8;
        handoff.result.outbound = outbound;
        handoff.result.pid = handoff_pid;
        handoff.result.dscp = tuples.dscp;
        handoff.result.decision_token = 0;
        handoff.result.mac.copy_from_slice(&mac);
        if let Some(pname) = handoff_pname {
            handoff.result.pname.copy_from_slice(pname);
        }
        crate::auxiliary::publish_handoff(&tuples.five, unsafe { &mut *scratch }, true)
            .map_err(|_| TC_ACT_SHOT)?;
        if !crate::contrack::tcp::commit_tcp_intercept(
            &tuples.five,
            u32::from_be_bytes(tcph.seq),
            pkt.incarnation,
        ) {
            return Err(TC_ACT_SHOT);
        }
    }

    redirect_to_control_plane_egress()
}

/// Fast-path decision after routing (shared by the cached and full-routing
/// UDP paths).
#[inline(always)]
fn fast_path_decision(
    ctx: &TcContext,
    link_h_len: u32,
    tuples: &Tuples,
    ethh: &EthHdr,
    outbound: u8,
    mark: u32,
    must: bool,
    mac: [u8; 6],
    handoff_pname: Option<&[u8; TASK_COMM_LEN]>,
    handoff_pid: u32,
    decision_token: u32,
    routing_generation: u64,
    trace_id: u32,
    direct_mark_index: u32,
    incarnation: u64,
) -> Verdict {
    let dns = tuples.five.dst_port == 53;
    if outbound == OUTBOUND_DIRECT && mark == 0 && (!dns || must) {
        ctx.set_mark(mark);
        return Err(TC_ACT_OK);
    } else if outbound == OUTBOUND_BLOCK {
        return Err(TC_ACT_SHOT);
    }

    let dns_route_mark = if dns {
        let route = if outbound == OUTBOUND_DIRECT && must && mark != 0 {
            if direct_mark_index > u8::MAX as u32 {
                return Err(TC_ACT_SHOT);
            }
            UdpDnsRoute::direct(direct_mark_index as u8, routing_generation)
        } else {
            UdpDnsRoute::new(outbound, routing_generation)
        };
        let Some(route) = route else {
            return Err(TC_ACT_SHOT);
        };
        route.to_mark()
    } else {
        0
    };

    if !wan_outbound_is_alive(ctx, outbound, IPPROTO_UDP, tuples.five.dst_port) {
        return Err(TC_ACT_SHOT);
    }

    let prepare_result = prep_redirect_to_control_plane(
        ctx,
        link_h_len,
        tuples,
        ethh,
        1,
        AuxPrep::Refresh,
        outbound,
        decision_token,
        incarnation,
    );
    if prepare_result != 0 {
        return Err(TC_ACT_SHOT);
    }

    unsafe {
        (*ctx.skb.skb).cb[0] = TPROXY_MARK;
        (*ctx.skb.skb).cb[1] = IPPROTO_UDP as u32;
        (*ctx.skb.skb).cb[2] = dns_route_mark;
        (*ctx.skb.skb).cb[3] = trace_id;
        (*ctx.skb.skb).cb[4] = crate::sk_lookup::udp_listener_marker(&tuples.five);
    }

    // Must UDP53 ownership (including the direct mark index) is entirely
    // per-packet. A tuple handoff could be overwritten before this skb arrives.
    if !(dns_route_mark != 0 && must) {
        let now = unsafe { bpf_ktime_get_ns() };
        let write_handoff = AuxPrep::Refresh
            .handoff_needs_publish(&tuples.five, decision_token, incarnation, now)
            .map_err(|_| TC_ACT_SHOT)?;
        if write_handoff {
            let Some(scratch) = UDP_DECISION_SCRATCH_MAP.get_ptr_mut(0) else {
                increment_bpf_stat(BpfStatsKey::RoutingHandoffInsertFailure);
                return Err(TC_ACT_SHOT);
            };
            let handoff: &mut RoutingHandoffEntry = unsafe { &mut (*scratch).handoff };
            unsafe { core::ptr::write_bytes(handoff, 0, 1) };
            handoff.last_seen_ns = now;
            handoff.routing_generation = if routing_generation != 0 {
                routing_generation
            } else {
                crate::route::captured_generation(trace_id)
            };
            handoff.trace_id = trace_id;
            handoff.incarnation = incarnation;
            handoff.result.mark = mark;
            handoff.result.must = must as u8;
            handoff.result.outbound = outbound;
            handoff.result.pid = handoff_pid;
            handoff.result.dscp = tuples.dscp;
            handoff.result.decision_token = decision_token;
            handoff.result.mac.copy_from_slice(&mac);
            if let Some(pname) = handoff_pname {
                handoff.result.pname.copy_from_slice(pname);
            }
            if let Err(error) =
                crate::auxiliary::publish_handoff(&tuples.five, unsafe { &mut *scratch }, false)
            {
                if dns || mark != 0 || error == TOKEN_IDENTITY_MISMATCH {
                    return Err(TC_ACT_SHOT);
                }
            }
        }
    }

    redirect_to_control_plane_egress()
}

/// WAN egress UDP handler.
#[inline(always)]
fn do_tproxy_wan_egress_udp(
    ctx: &TcContext,
    link_h_len: u32,
    pkt: &mut crate::transport::ParsedPacket,
) -> Verdict {
    let tuples = &pkt.tuples;
    let ethh = &pkt.ethh;
    let dns = tuples.five.dst_port == 53;
    let outbound: u8;
    let mark: u32;
    let must: bool;
    let mut mac: [u8; 6] = [0; 6];
    let mut handoff_pname: Option<&[u8; TASK_COMM_LEN]> = None;
    let mut handoff_pid: u32 = 0;
    let mut decision_token: u32 = 0;

    let proto = ctx.skb.protocol() as u16;
    let ip_version = if proto == ETH_P_IP.to_be() {
        IpVersionType::V4 as u8
    } else {
        IpVersionType::V6 as u8
    };

    let pid_pname_opt = socket_identity::lookup(ctx);
    if let Some(pid_pname) = pid_pname_opt {
        let param = PARAM.load();
        if pid_pname.pid == param.control_plane_pid {
            return Err(TC_ACT_UNSPEC);
        }
    }

    // A live non-DNS entry already carries a complete routing decision.
    // Lookup-only admission avoids allocating an empty entry before a miss is
    // routed and refreshes the cached entry's timestamp at most once per second.
    if !is_short_lived_udp_traffic(&tuples.five)
        && let Some(conn_state) = lookup_udp_seen(&tuples.five)
    {
        if conn_state.state == UdpDecisionState::Preparing as u8
            || conn_state.state == UdpDecisionState::Aborted as u8
        {
            return Err(TC_ACT_SHOT);
        }
        if conn_state.is_wan_ingress_direction != 0 {
            return Err(TC_ACT_UNSPEC);
        }

        let meta_raw = unsafe { conn_state.meta.raw };
        if (meta_raw >> 56) & 1 != 0 {
            outbound = (meta_raw & 0xFF) as u8;
            mark = ((meta_raw >> 8) & 0xFFFFFFFF) as u32;
            must = ((meta_raw >> 40) & 1) != 0;
            mac.copy_from_slice(&conn_state.mac);
            handoff_pname = Some(&conn_state.pname);
            handoff_pid = conn_state.pid;
            decision_token = conn_state.decision_token;

            return fast_path_decision(
                ctx,
                link_h_len,
                tuples,
                ethh,
                outbound,
                mark,
                must,
                mac,
                handoff_pname,
                handoff_pid,
                decision_token,
                0,
                conn_state.trace_id,
                u32::MAX,
                conn_state.incarnation,
            );
        }
    }

    if let Some(pid_pname) = pid_pname_opt {
        handoff_pname = Some(&pid_pname.pname);
        handoff_pid = pid_pname.pid;
    }

    let route_mac = if link_h_len == ETH_HLEN {
        mac.copy_from_slice(&ethh.src_addr);
        Some(&mac)
    } else {
        None
    };
    let pname = pid_pname_opt.map(|pid_pname| &pid_pname.pname);
    crate::route::build_input(
        &mut pkt.routing_input,
        tuples,
        route_mac,
        L4ProtoType::Udp as u8,
        ip_version,
        true,
    );
    let flags = crate::maps::datapath_flags();
    let (mut decision, generation) = match crate::route::route(
        &mut pkt.routing_input,
        pname,
        flags,
        &mut pkt.route_witness.output,
    ) {
        Ok(result) => result,
        Err(_) => return Err(TC_ACT_SHOT),
    };
    let routing_generation = generation;

    decision.apply_mode_flags(flags, tuples.five.dst_port);
    outbound = decision.handoff_outbound();
    mark = decision.mark;
    must = decision.must != 0;
    let trace_id = if outbound == OUTBOUND_BLOCK
        || (outbound == OUTBOUND_DIRECT && mark == 0 && (!dns || must))
    {
        0
    } else {
        crate::route::capture(&mut pkt.route_witness, &tuples.five, decision_token, false)
    };

    if !is_short_lived_udp_traffic(&tuples.five) {
        let must_u8 = must as u8;
        let pname = pid_pname_opt.map(|pid_pname| &pid_pname.pname);
        let pid = pid_pname_opt.map_or(0, |pid_pname| pid_pname.pid);
        let routing_meta_flags = if outbound == OUTBOUND_DIRECT && mark == 0 {
            ROUTING_META_FLAG_OFFLOAD
        } else if outbound != OUTBOUND_BLOCK {
            ROUTING_META_FLAG_WAN_USERSPACE
        } else {
            0
        };
        let state = mark_udp_seen(
            &tuples.five,
            0u8,
            Some(&outbound),
            Some(&mark),
            Some(&must_u8),
            Some(&mac),
            tuples.dscp,
            pname,
            pid,
            trace_id,
            routing_meta_flags,
        );
        if state.is_none() {
            if crate::maps::tuple_retiring(&tuples.five)
                || crate::maps::CONN_STATE_MAP.get_ptr(&tuples.five).is_some()
            {
                return Err(TC_ACT_SHOT);
            }
            if outbound == OUTBOUND_DIRECT && mark == 0 {
                return Err(TC_ACT_UNSPEC);
            }
            return Err(TC_ACT_SHOT);
        }
        pkt.incarnation = state.unwrap().incarnation;
    }

    fast_path_decision(
        ctx,
        link_h_len,
        tuples,
        ethh,
        outbound,
        mark,
        must,
        mac,
        handoff_pname,
        handoff_pid,
        decision_token,
        routing_generation,
        trace_id,
        decision.direct_mark_index,
        pkt.incarnation,
    )
}

/// WAN egress entry point: parse the packet first so the verifier accepts
/// direct `__sk_buff` field access, skip non-localhost traffic, then dispatch
/// to the TCP or UDP handler.
#[inline(always)]
fn do_tproxy_wan_egress(ctx: &TcContext, link_h_len: u32) -> Verdict {
    let scratch_key: u32 = 0;
    let pkt = match unsafe { PKT_SCRATCH_KEY.get_ptr_mut(scratch_key) } {
        Some(ptr) => unsafe { &mut *ptr },
        None => return Err(TC_ACT_SHOT),
    };

    // Parse before reading __sk_buff fields: ctx.load() proves to the verifier
    // that ctx.skb.skb is a valid non-null pointer.
    let ret = parse_packet(ctx, link_h_len, pkt);
    if ret != 0 {
        if ret == PARSE_FRAGMENT as c_long && crate::fragment::condemned(pkt) {
            return Err(TC_ACT_SHOT);
        }
        if local_ndp_redirect(ctx, ret) {
            return Err(TC_ACT_SHOT);
        }
        // Unsupported or malformed traffic is left untouched.
        return Err(TC_ACT_UNSPEC);
    }

    // An owned queue carrier must not escape through a WAN-role bridge port either.
    if pkt.l4proto == IPPROTO_UDP
        && pkt.tuples.five.dst_port == 53
        && UdpDnsRoute::from_nfqueue_mark(unsafe { (*ctx.skb.skb).mark }).is_some()
    {
        return Err(TC_ACT_SHOT);
    }
    if !crate::maps::datapath_ready() {
        return Err(TC_ACT_UNSPEC);
    }

    // Broadcast/multicast is never re-routed into daens.
    if crate::transport::dst_is_special(pkt, link_h_len) {
        return Err(TC_ACT_UNSPEC);
    }

    // Bypass locally-generated traffic destined for the honk host itself.
    // Without this, connections to the honk management port (e.g. 10.10.10.1:9999)
    // are intercepted and routed through the proxy, creating a loop.
    let param = PARAM.load();
    if param.local_ip != 0 {
        let dst_ip = pkt.tuples.five.dst_ip;
        let dst_ipv4 = unsafe { dst_ip.u6_addr32[3] };
        if dst_ip.is_v4_mapped() && dst_ipv4 == param.local_ip {
            return Err(TC_ACT_UNSPEC);
        }
    }

    // Pure forwarded traffic stays on the native path here; continue so a
    // downstream external-interface NAT classifier can still translate it.
    if skb_ingress_ifindex(ctx) != NOWHERE_IFINDEX {
        return Err(TC_ACT_UNSPEC);
    }

    // Global socket marks match exactly. Final userspace direct sockets carry
    // the same classified flag as native/NFQUEUE direct packets, independent
    // of cookie/PID availability. Pending queue tokens are never this bypass.
    let mark = skb_mark(ctx);
    if (param.dae_socket_mark != 0 && mark == param.dae_socket_mark)
        || mark & SKB_MARK_RESERVED_MASK == CLASSIFIED_MARK
    {
        return Err(TC_ACT_OK);
    }
    // TCP fence/expiry refusal happens inside conntrack and its post-miss check.
    if pkt.l4proto != IPPROTO_TCP && crate::contrack::tuple_unavailable(&pkt.tuples.five) {
        return Err(TC_ACT_SHOT);
    }
    let mut tcp_publisher = crate::contrack::tcp::TcpPublisher::new(&pkt.tuples.five);
    if pkt.l4proto == IPPROTO_TCP && is_new_tcp_connection(&pkt.tcph) {
        if !tcp_publisher.acquire(ctx, &pkt.tcph) {
            return Err(TC_ACT_SHOT);
        }
        pkt.incarnation = tcp_publisher.incarnation;
    }

    match pkt.l4proto {
        IPPROTO_TCP => do_tproxy_wan_egress_tcp(ctx, link_h_len, pkt, &tcp_publisher),
        IPPROTO_UDP => do_tproxy_wan_egress_udp(ctx, link_h_len, pkt),
        _ => Ok(TC_ACT_UNSPEC),
    }
}

// TC entry points use raw __sk_buff pointer for verifier compatibility.

#[unsafe(no_mangle)]
#[unsafe(link_section = "classifier")]
pub fn lan_egress_l2(ctx: *mut __sk_buff) -> i32 {
    flatten(do_tproxy_lan_egress(&TcContext::new(ctx), 14))
}

#[unsafe(no_mangle)]
#[unsafe(link_section = "classifier")]
pub fn lan_egress_l3(ctx: *mut __sk_buff) -> i32 {
    flatten(do_tproxy_lan_egress(&TcContext::new(ctx), 0))
}

#[unsafe(no_mangle)]
#[unsafe(link_section = "classifier")]
pub fn wan_egress_l2(ctx: *mut __sk_buff) -> i32 {
    crate::fragment::record(flatten(do_tproxy_wan_egress(&TcContext::new(ctx), 14)))
}

#[unsafe(no_mangle)]
#[unsafe(link_section = "classifier")]
pub fn wan_egress_l3(ctx: *mut __sk_buff) -> i32 {
    crate::fragment::record(flatten(do_tproxy_wan_egress(&TcContext::new(ctx), 0)))
}
